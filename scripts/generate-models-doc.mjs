/**
 * Generate docs/supported-models.md from src/knowledge.ts (the authoritative
 * data source). Run after every knowledge-base update:
 *
 *   node scripts/generate-models-doc.mjs
 *
 * The doc is a human-readable VIEW — never hand-edit it; edit knowledge.ts
 * and re-run this script.
 */
import { build } from 'esbuild'
import { pathToFileURL } from 'node:url'
import { writeFile, rm } from 'node:fs/promises'

const OUT = 'docs/supported-models.md'
const TMP = '.tmp-knowledge-doc.mjs'

// Bundle the self-contained knowledge module so plain node can import it.
await build({
  entryPoints: ['src/knowledge.ts'],
  bundle: true,
  format: 'esm',
  outfile: TMP,
  logLevel: 'silent',
})
const { KNOWLEDGE_BASE } = await import(pathToFileURL(TMP).href)
await rm(TMP, { force: true })

/** Vendor grouping by entry-id prefix, in the array's own order. */
const VENDORS = [
  ['deepseek', 'DeepSeek'],
  ['openai', 'OpenAI'],
  ['anthropic', 'Anthropic Claude'],
  ['google', 'Google Gemini'],
  ['xai', 'xAI Grok'],
  ['mistral', 'Mistral'],
  ['qwen', 'Qwen（通义千问）'],
  ['glm', 'GLM（智谱）'],
  ['kimi', 'Kimi（月之暗面）'],
  ['hunyuan', 'Hunyuan（腾讯混元）'],
  ['step', 'Step（阶跃星辰）'],
  ['doubao', 'Doubao（字节豆包）'],
  ['minimax', 'MiniMax'],
  ['mimo', 'Xiaomi MiMo'],
  ['baidu', 'Baidu ERNIE（文心）'],
]
const vendorOf = (id) => VENDORS.find(([prefix]) => id.startsWith(prefix))?.[1] ?? 'Other'

/** Group entries by vendor, preserving the knowledge base's own order. */
const groups = []
for (const entry of KNOWLEDGE_BASE) {
  const vendor = vendorOf(entry.id)
  const last = groups[groups.length - 1]
  if (last?.vendor === vendor) last.entries.push(entry)
  else groups.push({ vendor, entries: [entry] })
}

const cell = (text) => String(text).replace(/\|/g, '\\|').replace(/\n/g, ' ')

/** The level → wire-spelling column. */
const fmtEfforts = (entry) => {
  if (entry.efforts === false) return '—（无推理控制）'
  return Object.entries(entry.efforts)
    .map(([level, wire]) => (wire === null ? `${level} →（不发送）` : `${level} → ${wire}`))
    .join(' · ')
}

const fmtCompat = (compat) => {
  if (compat === undefined) return ''
  const parts = Object.entries(compat)
    .filter(([, value]) => value !== undefined)
    .map(([key, value]) => (typeof value === 'boolean' ? `${key}: ${value ? '✓' : '✗'}` : `${key}: ${value}`))
  return parts.join('；')
}

const fmtInput = (entry) => {
  if (entry.input === undefined) return '（继承）'
  return entry.input.includes('image') ? '✅' : '❌'
}

const fmtCapacity = (entry) => {
  if (entry.contextWindow === undefined && entry.maxTokens === undefined) return ''
  const context = entry.contextWindow === undefined ? '—' : entry.contextWindow.toLocaleString('en-US')
  const max = entry.maxTokens === undefined ? '—' : entry.maxTokens.toLocaleString('en-US')
  return `${context} / ${max}`
}

const rows = groups.map(({ vendor, entries }) => {
  const table = [
    `## ${vendor}`,
    '',
    '| 模型 / 匹配写法 | 档位 → wire 拼写 | 默认档 | 图片 | 容量（上下文 / 最大输出） | 兼容开关 |',
    '|---|---|---|---|---|---|',
    ...entries.map((entry) => {
      const patterns = entry.patterns.map((pattern) => `\`${pattern}\``).join('<br>')
      const model = `${cell(entry.id)}<br>${patterns}`
      const compat = [fmtCompat(entry.compat), entry.anthropicAdaptive === true ? 'anthropic 自适应思考钉扎' : '']
        .filter(Boolean).join('；')
      return `| ${model} | ${fmtEfforts(entry)} | ${entry.defaultEffort ?? '—'} | ${fmtInput(entry)} | ${fmtCapacity(entry)} | ${cell(compat)} |`
    }),
    '',
  ]
  // The notes are long: render them as a per-vendor list under the table.
  const notes = entries
    .filter((entry) => entry.note !== undefined)
    .map((entry) => `- **\`${entry.id}\`**：${entry.note}`)
  return { vendor, table, notes, entries }
})

const total = KNOWLEDGE_BASE.length
const withLadder = KNOWLEDGE_BASE.filter((entry) => entry.efforts !== false).length
const withVision = KNOWLEDGE_BASE.filter((entry) => entry.input?.includes('image')).length

const header = `<!-- GENERATED by scripts/generate-models-doc.mjs from src/knowledge.ts — do not edit by hand. Re-run: node scripts/generate-models-doc.mjs -->

# 支持的模型知识库 / Supported models

> **数据源**：[\`src/knowledge.ts\`](../src/knowledge.ts) —— 这是 Auto-adapt 实际使用的权威数据；本文件由脚本生成，供人工查阅，请勿手编（改知识库后重跑 \`node scripts/generate-models-doc.mjs\`）。
>
> **Data source**: [\`src/knowledge.ts\`](../src/knowledge.ts), the authoritative set Auto-adapt actually consults. This file is generated — edit the source and re-run the script.

当前共 **${total}** 个条目（${withLadder} 个带推理档位，${total - withLadder} 个声明为无推理控制；${withVision} 个声明图片输入）。核对基线：2026-08 对照各厂商官方文档全量复核并交叉核对公开目录；2026-09 增补（DeepSeek V4.1-Flash、Step-5-Preview、MiMo v2.5–2.6、Grok 4.7）。

**图例**

- **档位 → wire 拼写**：选该档位时发给供应商的实际 \`reasoning_effort\` 字符串；\`off →（不发送）\` 表示该档不发参数；\`—（无推理控制）\` 表示该家族没有任何档位控制（\`efforts: false\`），Auto-adapt 不会建议档位。
- **图片**：✅ = 会声明图片输入（\`input: ["text", "image"]\`）；❌ = 声明为纯文本；（继承）= 该条目不给出模态建议。
- **容量**：参考值（上下文 / 最大输出），仅在 UI 中作只读提示，永远不会被自动填进官方容量输入框。
- 匹配写法为小写子串匹配，命中任一写法即归入该条目。
`

const body = rows
  .map(({ table, notes }) => [...table, ...(notes.length > 0 ? ['**条目备注**', '', ...notes, ''] : [])].join('\n'))
  .join('\n')

await writeFile(OUT, `${header}\n${body}\n`, 'utf8')
console.log(`wrote ${OUT}: ${total} entries, ${groups.length} vendors`)
